"""Generate native 4bpp landscape tiles; no external art dependencies."""
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
tiles = [bytes(32)]
lookup = {tiles[0]: 0}
maps = []
for region in range(3):
    pixels = [[0]*256 for _ in range(256)]
    ox = region*80
    def rect(x,y,w,h,c):
        for yy in range(max(y,0),min(y+h,256)):
            for xx in range(max(x+ox,0),min(x+ox+w,256)):
                pixels[yy][xx]=c
    def tri(x,y,w,h,c):
        for dy in range(h):
            half = max(1,w*(dy+1)//(2*h))
            rect(x+w//2-half,y+dy,half*2,1,c)
    # Angular coastline and exposed strata, joining into one landmass.
    for x in range(80):
        top = 109 + ((x+region*13)//13)%3
        bottom = 139-abs(x-40)//9
        rect(x,top,1,bottom-top,4)
        rect(x,bottom,1,4,3)
        rect(x,bottom+4,1,2,2)
        rect(x,top,1,2,5)
    # Ridgeline silhouettes.
    for x,y,w,h in [(0,89,36,25),(25,82,44,32),(55,94,25,20)]:
        tri(x,y,w,h,3)
    def tree(x,y):
        rect(x+5,y+13,2,7,8)
        tri(x,y,12,12,3)
        tri(x-2,y+5,16,12,5)
        tri(x+1,y+5,8,9,4)
    if region == 0:
        for x,y in [(5,101),(60,99),(69,112)]: tree(x,y)
        for x,y in [(19,109),(43,118)]:
            rect(x,y,20,16,10); rect(x+2,y+2,16,12,9)
            tri(x-3,y-10,26,12,7); rect(x-3,y,26,3,6)
            rect(x+8,y+7,5,9,1);rect(x+3,y+4,3,4,11)
        rect(33,125,5,11,8)
    elif region == 1:
        for x,y in [(4,101),(60,102),(68,114)]: tree(x,y)
        rect(30,89,20,39,8)
        for y,w in [(87,30),(98,36),(110,42)]:
            rect(40-w//2,y,w,3,11)
            tri(40-w//2,y-7,w,8,6)
            rect(33,y+4,14,7,9)
            rect(38,y+4,4,7,1)
        rect(36,124,8,9,1)
        rect(27,133,26,3,8)
    else:
        tri(11,82,52,42,8);tri(27,84,30,39,6)
        rect(31,85,13,4,7);rect(35,89,5,12,7)
        for x,y in [(31,75),(36,68),(32,62)]: rect(x,y,10,4,3)
        for x,y in [(7,111),(65,110)]:
            rect(x+5,y+6,2,18,8)
            rect(x-3,y+5,20,3,5);rect(x,y+2,14,3,4)
            rect(x+4,y,6,3,5)
        rect(25,127,29,2,12);rect(31,132,34,2,12)
    tilemap=[]
    for ty in range(32):
        for tx in range(32):
            tile=bytes(pixels[ty*8+y][tx*8+x] | pixels[ty*8+y][tx*8+x+1]<<4 for y in range(8) for x in range(0,8,2))
            if tile not in lookup:
                lookup[tile]=len(tiles);tiles.append(tile)
            tilemap.append(lookup[tile])
    maps.append(tilemap)
assert len(tiles)*32 < 0x5800, len(tiles)
def array(name,typ,values):
    return f'static const {typ} {name}[] = {{\n'+''.join('    '+', '.join(hex(v) for v in values[i:i+16])+',\n' for i in range(0,len(values),16))+'};\n'
out='// Generated by plastic_ox/title/generate_art.py.\n'
out+=array('sLandscapeTiles','u32',[int.from_bytes(b''.join(tiles)[i:i+4],'little') for i in range(0,len(tiles)*32,4)])
for i,m in enumerate(maps): out+=array('sLandscapeMap'+str(i),'u16',m)
(ROOT/'src/data/plastic_ox_title_art.h').write_text(out)
print(f'{len(tiles)} unique landscape tiles')

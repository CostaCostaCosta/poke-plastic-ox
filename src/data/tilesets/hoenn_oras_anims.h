static void TilesetAnim_HoennOrasGeneral(u16 timer);
static void QueueAnimTiles_HoennOrasGeneral_Flower(u16 timer);
static void QueueAnimTiles_HoennOrasGeneral_Water(u16 timer);
static void QueueAnimTiles_HoennOrasGeneral_SandWaterEdge(u16 timer);
static void QueueAnimTiles_HoennOrasGeneral_Waterfall(u16 timer);
static void QueueAnimTiles_HoennOrasGeneral_LandWaterEdge(u16 timer);

static void TilesetAnim_HoennOrasGeneral(u16 timer)
{
    if (timer % 16 == 0)
        QueueAnimTiles_HoennOrasGeneral_Flower(timer / 16);
    if (timer % 16 == 1)
        QueueAnimTiles_HoennOrasGeneral_Water(timer / 16);
    if (timer % 16 == 2)
        QueueAnimTiles_HoennOrasGeneral_SandWaterEdge(timer / 16);
    if (timer % 16 == 3)
        QueueAnimTiles_HoennOrasGeneral_Waterfall(timer / 16);
    if (timer % 16 == 4)
        QueueAnimTiles_HoennOrasGeneral_LandWaterEdge(timer / 16);
}

static void QueueAnimTiles_HoennOrasGeneral_Flower(u16 timer)
{
    u16 i = timer % ARRAY_COUNT(gTilesetAnims_HoennOrasGeneral_Flower);
    AppendTilesetAnimToBuffer(gTilesetAnims_HoennOrasGeneral_Flower[i], (u16 *)(BG_VRAM + TILE_OFFSET_4BPP(508)), 4 * TILE_SIZE_4BPP);
}

static void QueueAnimTiles_HoennOrasGeneral_Water(u16 timer)
{
    u8 i = timer % ARRAY_COUNT(gTilesetAnims_HoennOrasGeneral_Water);
    AppendTilesetAnimToBuffer(gTilesetAnims_HoennOrasGeneral_Water[i], (u16 *)(BG_VRAM + TILE_OFFSET_4BPP(432)), 30 * TILE_SIZE_4BPP);
}

static void QueueAnimTiles_HoennOrasGeneral_SandWaterEdge(u16 timer)
{
    u16 i = timer % ARRAY_COUNT(gTilesetAnims_HoennOrasGeneral_SandWaterEdge);
    AppendTilesetAnimToBuffer(gTilesetAnims_HoennOrasGeneral_SandWaterEdge[i], (u16 *)(BG_VRAM + TILE_OFFSET_4BPP(464)), 10 * TILE_SIZE_4BPP);
}

static void QueueAnimTiles_HoennOrasGeneral_Waterfall(u16 timer)
{
    u16 i = timer % ARRAY_COUNT(gTilesetAnims_HoennOrasGeneral_Waterfall);
    AppendTilesetAnimToBuffer(gTilesetAnims_HoennOrasGeneral_Waterfall[i], (u16 *)(BG_VRAM + TILE_OFFSET_4BPP(496)), 6 * TILE_SIZE_4BPP);
}

static void QueueAnimTiles_HoennOrasGeneral_LandWaterEdge(u16 timer)
{
    u16 i = timer % ARRAY_COUNT(gTilesetAnims_HoennOrasGeneral_LandWaterEdge);
    AppendTilesetAnimToBuffer(gTilesetAnims_HoennOrasGeneral_LandWaterEdge[i], (u16 *)(BG_VRAM + TILE_OFFSET_4BPP(480)), 10 * TILE_SIZE_4BPP);
}

void InitTilesetAnim_HoennOrasGeneral(void)
{
    sPrimaryTilesetAnimCounter = 0;
    sPrimaryTilesetAnimCounterMax = 256;
    sPrimaryTilesetAnimCallback = TilesetAnim_HoennOrasGeneral;
}

// Rustboro's ORAS fountain frames differ from Emerald's. Windy-water frames
// retain the same tiles and schedule in both implementations.
static const u16 sHoennOrasRustboroFountain0[] = INCGFX_U16("data/tilesets/secondary/hoenn_oras_rustboro/anim/fountain/0.png", ".4bpp");
static const u16 sHoennOrasRustboroFountain1[] = INCGFX_U16("data/tilesets/secondary/hoenn_oras_rustboro/anim/fountain/1.png", ".4bpp");
static void TilesetAnim_HoennOrasRustboro(u16 timer)
{
    QueueAnimTiles_Rustboro_WindyWater(timer / 8, timer % 8);
    if (timer % 8 == 0)
        AppendTilesetAnimToBuffer((timer / 8) % 2 ? sHoennOrasRustboroFountain1 : sHoennOrasRustboroFountain0,
            (u16 *)(BG_VRAM + TILE_OFFSET_4BPP(NUM_TILES_IN_PRIMARY + 448)), 4 * TILE_SIZE_4BPP);
}

void InitTilesetAnim_HoennOrasRustboro(void)
{
    sSecondaryTilesetAnimCounter = 0;
    sSecondaryTilesetAnimCounterMax = sPrimaryTilesetAnimCounterMax;
    sSecondaryTilesetAnimCallback = TilesetAnim_HoennOrasRustboro;
}
